#!/usr/bin/env bash
# Install good-practice rules for Claude Code into <path>/.claude for every technology found under <path>.
#
# Usage: install.sh [--dry-run] [--all] [path]      (path defaults to the current directory)
#        install.sh --user-scope [--dry-run]        install every rule into ~/.claude, for all projects
#        install.sh --install-cmd                   put the `good-practices` command on the PATH
#
#   macOS/Linux: bash. Windows: Git Bash (ships with Git for Windows, which Claude Code also uses).
#
#   Walks <path> recursively (skipping node_modules, .git, dist, build, target, venv...) and collects
#   the file extensions. If <path> holds several repos, it installs the rules for all of them.
#   Writes <path>/.claude/rules/good-practices/*.md; each rule loads by itself when Claude touches a
#   file in its language. Never deletes anything: adds what is missing, updates its own files, backs up
#   foreign ones first, and moves its own files that a newer version no longer ships into the backup.
#
#   --dry-run      show what it would do without writing
#   --all          install every rule regardless of the extensions found
#   --user-scope   install every rule into ~/.claude/rules/good-practices; each rule still loads only
#                  when Claude touches its language (don't combine with a per-project install)
#   --install-cmd  create `good-practices` (plus `good-practices.cmd` on Windows) in ~/.local/bin
#                  (~/bin on Windows), or in $GOOD_PRACTICES_BIN. Run it again if you move this folder.
set -euo pipefail

readonly PKG="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
readonly MARK="Installed by good-practices-rules"
readonly DEST_REL=".claude/rules/good-practices"
readonly PRUNE_DIRS=".git node_modules bower_components .venv venv env __pycache__ .pytest_cache .mypy_cache
.tox site-packages dist build out target bin obj .gradle .angular .next .nuxt .svelte-kit coverage vendor
.idea .vscode .terraform .claude"

DRY=0
ALL=0
USER_SCOPE=0
TARGET="."
TARGET_SET=0
NEW=0
UPD=0
SAME=0
OBSOLETE=0
BACKUP_DIR=""

die() {
  local msg="$1"
  echo "error: $msg" >&2
  exit 1
}

usage() {
  awk 'NR > 1 && /^set -/ { exit } NR > 1' "$0" | sed 's/^# \{0,1\}//'
  exit 0
}

is_windows() {
  case "$(uname -s)" in
    MINGW*|MSYS*|CYGWIN*) return 0 ;;
    *) return 1 ;;
  esac
}

# Put `good-practices` on the PATH: a wrapper that calls this install.sh (not a symlink, which Git Bash
# on Windows copies instead of linking). On Windows it also writes a .cmd for cmd and PowerShell.
install_cmd() {
  local bin_dir
  local self="$PKG/install.sh"
  if is_windows; then
    bin_dir="${GOOD_PRACTICES_BIN:-$HOME/bin}"
  else
    bin_dir="${GOOD_PRACTICES_BIN:-$HOME/.local/bin}"
  fi
  mkdir -p "$bin_dir"
  printf '#!/usr/bin/env bash\n# Generated by good-practices-rules (install.sh --install-cmd).\nexec bash %q "$@"\n' \
    "$self" > "$bin_dir/good-practices"
  chmod +x "$bin_dir/good-practices"
  echo "==> created $bin_dir/good-practices -> $self"
  if is_windows; then
    printf '@echo off\r\n"%s" "%s" %%*\r\n' "$(cygpath -w "$(command -v bash)")" "$self" > "$bin_dir/good-practices.cmd"
    echo "==> created $bin_dir/good-practices.cmd (cmd and PowerShell)"
    echo "    To use it outside Git Bash, add $(cygpath -w "$bin_dir") to your user Path (PowerShell):"
    echo "    [Environment]::SetEnvironmentVariable('Path', [Environment]::GetEnvironmentVariable('Path','User') + ';$(cygpath -w "$bin_dir")', 'User')"
  fi
  if [[ ":$PATH:" != *":$bin_dir:"* ]]; then
    echo "==> warning: $bin_dir is not on the PATH. Add this to your ~/.zshrc or ~/.bashrc:"
    echo "    export PATH=\"$bin_dir:\$PATH\""
  fi
  echo "    Usage: good-practices [--dry-run] [--all] [path] | good-practices --user-scope"
  return 0
}

# Print, one per line, the lowercase extensions and special markers found under root.
scan_tokens() {
  local root="$1"
  local prune=()
  local d
  for d in $PRUNE_DIRS; do
    prune+=(-name "$d" -o)
  done
  unset 'prune[${#prune[@]}-1]'
  find "$root" \( -type d \( "${prune[@]}" \) -prune \) -o -type f -print 2>/dev/null |
    awk -F/ '{
      name = $NF
      if (name ~ /^(Dockerfile|Containerfile)/ || tolower(name) ~ /\.dockerfile$/) print "@docker"
      if (name == "angular.json") print "@angular"
      if (name ~ /\.component\.ts$/) print "@angular"
      n = split(name, parts, ".")
      if (n > 1 && parts[1] != "") print tolower(parts[n])
    }' | sort -u
  return 0
}

# Map an extension or marker to its rule files.
rules_for() {
  local token="$1"
  case "$token" in
    ts|tsx|js|jsx|mjs|cjs|mts|cts) echo "typescript typescript-style typescript-tests general" ;;
    @angular) echo "angular typescript typescript-style typescript-tests html css general" ;;
    java) echo "java java-style java-tests general" ;;
    py|pyi) echo "python python-tests general" ;;
    go) echo "go general" ;;
    php) echo "php general" ;;
    kt|kts) echo "general" ;;
    html|htm) echo "html" ;;
    css|scss|sass|less) echo "css" ;;
    xml|xsd|xsl|xslt|wsdl) echo "xml" ;;
    sh|bash|zsh|ksh) echo "shell" ;;
    sql|pks|pkb|pls|plb|pck|trg) echo "plsql" ;;
    ps1|psm1|psd1) echo "powershell" ;;
    @docker) echo "docker" ;;
    *) echo "" ;;
  esac
  return 0
}

# Copy src to dst: create it, update it if it is ours, or back it up first if it came from elsewhere.
put() {
  local src="$1"
  local dst="$2"
  local rel="${dst#"$TARGET"/}"
  if [[ -f "$dst" ]]; then
    if cmp -s "$src" "$dst"; then
      SAME=$((SAME + 1))
      return 0
    fi
    if grep -q "$MARK" "$dst"; then
      echo "  ~ $rel"
    else
      echo "  ~ $rel (not from this package; backed up to ${BACKUP_DIR#"$TARGET"/})"
      if [[ $DRY -eq 0 ]]; then
        mkdir -p "$BACKUP_DIR"
        cp -p "$dst" "$BACKUP_DIR/"
      fi
    fi
    UPD=$((UPD + 1))
  else
    echo "  + $rel"
    NEW=$((NEW + 1))
  fi
  if [[ $DRY -eq 0 ]]; then
    mkdir -p "$(dirname "$dst")"
    cp "$src" "$dst"
  fi
  return 0
}

# Move into the backup folder every file of ours that this version no longer ships, so a renamed or
# removed rule never sits next to its replacement.
retire_obsolete() {
  local dir="$1"
  local file
  for file in "$dir"/*.md; do
    [[ -f "$file" ]] || continue
    [[ ! -f "$PKG/rules/$(basename "$file")" ]] || continue
    grep -q "$MARK" "$file" || continue
    echo "  - ${file#"$TARGET"/} (no longer in the package; moved to ${BACKUP_DIR#"$TARGET"/})"
    OBSOLETE=$((OBSOLETE + 1))
    if [[ $DRY -eq 0 ]]; then
      mkdir -p "$BACKUP_DIR"
      mv "$file" "$BACKUP_DIR/"
    fi
  done
  return 0
}

main() {
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --dry-run) DRY=1 ;;
      --all) ALL=1 ;;
      --user-scope) USER_SCOPE=1 ;;
      --install-cmd) install_cmd; exit 0 ;;
      -h|--help) usage ;;
      -*) die "unknown option: $1 (see --help)" ;;
      *) TARGET="$1"; TARGET_SET=1 ;;
    esac
    shift
  done
  if [[ $USER_SCOPE -eq 1 ]]; then
    [[ $TARGET_SET -eq 0 ]] || die "--user-scope installs into ~/.claude; it takes no path"
    TARGET="$HOME"
    ALL=1
  fi
  [[ -d "$TARGET" ]] || die "directory not found: $TARGET"
  [[ -d "$PKG/rules" ]] || die "missing $PKG/rules"
  TARGET="$(cd "$TARGET" && pwd)"
  [[ "$TARGET" != "$PKG" ]] || die "the target is this package itself"
  BACKUP_DIR="$TARGET/.claude/good-practices-backup/$(date +%Y%m%d-%H%M%S)"

  local wanted="00-how-to secrets repo"
  local found=""
  local token
  local mapped
  if [[ $ALL -eq 1 ]]; then
    wanted="$wanted $(cd "$PKG/rules" && ls ./*.md | sed 's|^\./||; s/\.md$//' | tr '\n' ' ')"
  else
    while IFS= read -r token; do
      mapped="$(rules_for "$token")"
      if [[ -n "$mapped" ]]; then
        found="$found ${token#@}"
        wanted="$wanted $mapped"
      fi
    done < <(scan_tokens "$TARGET")
  fi
  wanted="$(echo "$wanted" | tr ' ' '\n' | sed '/^$/d' | sort -u | tr '\n' ' ')"

  echo "==> target : $TARGET/.claude"
  if [[ $USER_SCOPE -eq 1 ]]; then
    echo "==> scope  : global, every project (each rule loads when Claude touches its language)"
  elif [[ $ALL -eq 1 ]]; then
    echo "==> found  : everything (--all)"
  else
    echo "==> found  :${found:- nothing recognizable; common rules only}"
  fi
  [[ $DRY -eq 0 ]] || echo "==> DRY RUN: nothing is written"

  local rule
  for rule in $wanted; do
    [[ -f "$PKG/rules/$rule.md" ]] || die "missing $PKG/rules/$rule.md"
    put "$PKG/rules/$rule.md" "$TARGET/$DEST_REL/$rule.md"
  done
  retire_obsolete "$TARGET/$DEST_REL"

  local other
  other="$(grep -L "$MARK" "$TARGET/$DEST_REL"/*.md 2>/dev/null || true)"
  if [[ -n "$other" ]]; then
    echo "==> warning: these files in $DEST_REL/ are not from this package and may repeat rules:"
    echo "$other" | sed "s|^$TARGET/|    |"
  fi
  if [[ $USER_SCOPE -eq 0 ]] && grep -qs "$MARK" "$HOME/$DEST_REL/00-how-to.md"; then
    echo "==> warning: the rules are also installed globally (~/$DEST_REL); with both, Claude loads each rule twice."
    echo "    Keep one. Drop the global install: rm -r ~/$DEST_REL"
    echo "    or this project's:                rm -r \"$TARGET/$DEST_REL\""
  fi
  echo "==> new: $NEW, updated: $UPD, unchanged: $SAME, retired: $OBSOLETE"
  if [[ $USER_SCOPE -eq 1 ]]; then
    echo "    They apply to every project from the next Claude Code session."
  else
    echo "    Open Claude Code in $TARGET so it picks up the rules for every repo inside it."
  fi
  return 0
}

main "$@"
